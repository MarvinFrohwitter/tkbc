/**
 * @brief Embeds the TCC runtime archives (libtcc1.a) into a generated C header.
 *
 * TCC only knows how to read libtcc1.a from the file system. The generated
 * header stores the bytes of the archives so the executables can write them
 * to a temporary directory at runtime and add that directory to TCC's library
 * search paths (see src/choreographer/tkbc-libtcc-runtime.c).
 *
 * Usage:
 *   libtcc1_2h -o <output.h> --linux <libtcc1.a> --windows <libtcc1.a>
 */

#include <errno.h>
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define BYTES_PER_LINE 20

static bool write_archive(FILE *out, const char *path, const char *label) {
    FILE *in = fopen(path, "rb");
    if (in == NULL) {
        fprintf(stderr, "[ERROR] Could not open %s: %s\n", path, strerror(errno));
        return false;
    }

    fprintf(out, "/* %s */\n", label);
    fprintf(out, "static const unsigned char tkbc_embedded_libtcc1[] = {\n");

    unsigned char buffer[8192];
    size_t column = 0;
    size_t bytes = 0;
    for (;;) {
        size_t n = fread(buffer, 1, sizeof(buffer), in);
        if (n == 0) {
            break;
        }
        for (size_t i = 0; i < n; ++i) {
            if (column == 0) {
                fputs("    ", out);
            }
            fprintf(out, "0x%02x,", buffer[i]);
            ++bytes;
            if (++column == BYTES_PER_LINE) {
                fputc('\n', out);
                column = 0;
            }
        }
    }

    bool ok = true;
    if (ferror(in)) {
        fprintf(stderr, "[ERROR] Could not read %s: %s\n", path, strerror(errno));
        ok = false;
    }
    if (bytes == 0) {
        fprintf(stderr, "[ERROR] The archive %s is empty.\n", path);
        ok = false;
    }
    if (column != 0) {
        fputc('\n', out);
    }
    fprintf(out, "};\n");

    if (fclose(in) != 0) {
        fprintf(stderr, "[ERROR] Could not close %s: %s\n", path, strerror(errno));
        ok = false;
    }
    fprintf(stderr, "[INFO] Embedded %zu bytes from %s\n", bytes, path);
    return ok;
}

static void usage(const char *prog_name) {
    fprintf(stderr, "Usage: %s -o <output.h> --linux <libtcc1.a> --windows <libtcc1.a>\n", prog_name);
    exit(EXIT_FAILURE);
}

int main(int argc, char **argv) {
    const char *out_path = NULL;
    const char *linux_path = NULL;
    const char *windows_path = NULL;

    for (int i = 1; i < argc; ++i) {
        if (strcmp(argv[i], "-o") == 0) {
            if (++i >= argc) usage(argv[0]);
            out_path = argv[i];
        } else if (strcmp(argv[i], "--linux") == 0) {
            if (++i >= argc) usage(argv[0]);
            linux_path = argv[i];
        } else if (strcmp(argv[i], "--windows") == 0) {
            if (++i >= argc) usage(argv[0]);
            windows_path = argv[i];
        } else {
            usage(argv[0]);
        }
    }
    if (!out_path || !linux_path || !windows_path) {
        usage(argv[0]);
    }

    char tmp_path[1024];
    if (snprintf(tmp_path, sizeof(tmp_path), "%s.tmp", out_path) >= (int)sizeof(tmp_path)) {
        fprintf(stderr, "[ERROR] The output path is too long: %s\n", out_path);
        return EXIT_FAILURE;
    }

    FILE *out = fopen(tmp_path, "wb");
    if (out == NULL) {
        fprintf(stderr, "[ERROR] Could not create %s: %s\n", tmp_path, strerror(errno));
        return EXIT_FAILURE;
    }

    fputs("#ifndef TKBC_LIBTCC1_HEADER_H_\n", out);
    fputs("#define TKBC_LIBTCC1_HEADER_H_\n\n", out);
    fputs("/* Generated by metaprogramming/libtcc1_2h.c. Do not edit. */\n\n", out);
    fputs("#ifdef _WIN32\n", out);
    bool ok = write_archive(out, windows_path, "Windows libtcc1.a");
    fputs("#else\n", out);
    ok = write_archive(out, linux_path, "Linux libtcc1.a") && ok;
    fputs("#endif\n\n", out);
    fputs("#endif // TKBC_LIBTCC1_HEADER_H_\n", out);

    if (fclose(out) != 0) {
        fprintf(stderr, "[ERROR] Could not close %s: %s\n", tmp_path, strerror(errno));
        ok = false;
    }
    if (!ok) {
        remove(tmp_path);
        return EXIT_FAILURE;
    }

    remove(out_path);
    if (rename(tmp_path, out_path) != 0) {
        fprintf(stderr, "[ERROR] Could not rename %s to %s: %s\n", tmp_path, out_path, strerror(errno));
        remove(tmp_path);
        return EXIT_FAILURE;
    }
    return EXIT_SUCCESS;
}
